#!/usr/bin/env python3
"""Render the deterministic (no-AI) markdown tables straight from the raw crawl.

Usage: python -I render_static.py <evidence_dir> <repo_eic_data_dir> "<snapshot label>"
Writes: gallery-tree.md, frame-sets.md, movies.md
"""
import datetime as dt
import json
import os
import re
import sys

E, OUT, SNAP = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(OUT, exist_ok=True)


def load(n):
    return json.load(open(os.path.join(E, n), encoding="utf-8"))


pages = load("pages.json")
edges = load("tree.json")
downloads = load("downloads.json")
framesets = load("framesets.json")
probes = load("probes.json")
OFFICIAL = {13786, 5313, 3912, 5669, 5533, 5425, 5196, 5011, 4960, 4950}
HDR = ("> Generated by script from NASA SVS records (no AI interpretation). Snapshot: %s.\n"
       "> Source: https://svs.gsfc.nasa.gov/api/<id> , each page's Download menus, and each frame-set folder listing.\n"
       "> Regenerate: see `README.md` in this folder.\n\n") % SNAP


def human(n):
    if not n:
        return "?"
    for u in ("B", "KB", "MB", "GB"):
        if n < 1000:
            return "%.1f %s" % (n, u)
        n /= 1000.0
    return "%.1f TB" % n


def esc(s):
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def decode(name):
    m = re.search(r"(20\d{2})(\d{3})(\d{2})(\d{2})(?!\d)", name)
    if m and 1 <= int(m.group(2)) <= 366 and int(m.group(3)) < 24 and int(m.group(4)) < 60:
        return "YYYYDDDHHMM", dt.datetime(int(m.group(1)), 1, 1) + dt.timedelta(
            days=int(m.group(2)) - 1, hours=int(m.group(3)), minutes=int(m.group(4)))
    m = re.search(r"(?<!\d)(20\d{2})(\d{2})(\d{2})(?!\d)", name)
    if m and 1 <= int(m.group(2)) <= 12 and 1 <= int(m.group(3)) <= 31:
        return "YYYYMMDD", dt.datetime(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    m = re.search(r"(?<!\d)(20\d{2})(\d{3})(?!\d)", name)
    if m and 1 <= int(m.group(2)) <= 366:
        return "YYYYDDD (day of year)", dt.datetime(int(m.group(1)), 1, 1) + dt.timedelta(days=int(m.group(2)) - 1)
    return None


# ---------------------------------------------------------------- gallery tree
kids = {}
for e in edges:
    kids.setdefault(e["parent"], []).append(e)
L = ["# EIC gallery tree (NASA SVS gallery 40467)\n", HDR,
     "Every page reachable from https://svs.gsfc.nasa.gov/gallery/earth-information-center/ , plus the 10 pages named in the",
     "official Jukebox resource list. `official` = named in the challenge's NASA Data & Resources list.",
     "`page updated` is the SVS page record's update date; it is NOT proof the files changed that day (see frame-sets.md / movies.md for file times).\n"]


def walk(pid, depth, seen):
    for e in kids.get(pid, []):
        c = pages.get(str(e["child"])) if e["child"] else None
        mc = (c or {}).get("media_counts", {})
        counts = ", ".join("%s %s" % (v, k) for k, v in mc.items() if not str(k).startswith("other"))
        L.append("%s- **%s** — %s (%s) | section: %s | released %s | page updated %s%s%s" % (
            "  " * depth, e["child"] or "(media group)", e["child_title"], (c or {}).get("page_type") or e["child_type"],
            e["section"], ((c or {}).get("release_date") or "")[:10] or "?", ((c or {}).get("update_date") or "")[:10] or "?",
            " | **official**" if e["child"] in OFFICIAL else "", (" | " + counts) if counts else ""))
        if c and c["page_type"] == "Gallery" and e["child"] not in seen:
            seen.add(e["child"])
            walk(e["child"], depth + 1, seen)


walk(40467, 0, set())
in_tree = {e["child"] for e in edges if e["child"]}
L.append("\n## Official Jukebox resources that are NOT linked from the gallery tree\n")
for pid in sorted(OFFICIAL - in_tree):
    L.append("- **%d** — %s (%s) | released %s" % (pid, pages[str(pid)]["title"], pages[str(pid)]["page_type"], pages[str(pid)]["release_date"][:10]))
tot = {}
for p in pages.values():
    tot[p["page_type"]] = tot.get(p["page_type"], 0) + 1
L.append("\n## Totals\n")
L.append("- Pages crawled: %d (%s)" % (len(pages), ", ".join("%d %s" % (v, k) for k, v in sorted(tot.items(), key=lambda kv: -kv[1]))))
cats = {}
for d in downloads:
    cats[d["category"]] = cats.get(d["category"], 0) + 1
L.append("- Download-menu entries: %d (%s)" % (len(downloads), ", ".join("%d %s" % (v, k) for k, v in sorted(cats.items(), key=lambda kv: -kv[1]))))
mv = [d for d in downloads if d["category"] == "movies"]
L.append("- Total size of all %d movie files: %s" % (len(mv), human(sum((d.get("head") or {}).get("bytes") or 0 for d in mv))))
open(os.path.join(OUT, "gallery-tree.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")

# ---------------------------------------------------------------- frame sets


def flat(r, out, prefix=""):
    rr = dict(r)
    rr["label"] = prefix + r["name"] if not prefix else prefix
    out.append(rr)
    for c in r.get("children") or []:
        c2 = dict(c)
        c2["page"], c2["group"] = r["page"], r["group"]
        c2["name"] = r["name"]
        c2["width"], c2["height"] = r.get("width"), r.get("height")
        c2["page_reported_items"] = None
        flat(c2, out, r["name"] + "/" + c["url"].rstrip("/").rsplit("/", 1)[-1])
    return out


allsets = []
for r in framesets:
    flat(r, allsets)
L = ["# Every frame-sequence folder in the EIC gallery (%d folders incl. sub-folders)\n" % len(allsets), HDR,
     "A *frame set* is a folder of numbered still images, one per movie frame. Columns:",
     "- **files**: how many files the folder listing shows today (the SVS page's own count is in brackets when it differs; some SVS counts include a header row, and counts such as 65536 / 131072 / 262144 are placeholders).",
     "- **listable**: HTTP status of the folder URL. 403 = the folder cannot be listed, but single files still download if the exact name is known.",
     "- **dates decoded from names**: only filled when the first and last file names contain a date; `step` = (last - first) / (files - 1).",
     "- **files modified**: timestamps as printed by the SVS listing (appear to be US Eastern time); empty when that listing layout has no dates.",
     "- Formats: EXR and TIFF cannot be shown by a browser and need conversion; PNG and JPEG can.\n"]
cur = None
for r in sorted(allsets, key=lambda r: (r["page"], r["url"])):
    if r["page"] != cur:
        cur = r["page"]
        L.append("\n## %d — %s\n" % (cur, pages[str(cur)]["title"]))
        L.append("| frame set | pixels | files | format | listable | first file → last file | index / dates decoded from names | files modified | folder URL |")
        L.append("|---|---|---|---|---|---|---|---|---|")
    n = r.get("n_files")
    rep = r.get("page_reported_items")
    files = ("%s" % n if n is not None else "?") + ((" [page says %s]" % rep) if rep not in (None, n) else "")
    fmt = ", ".join("%s×%s" % (v, k or "(no ext)") for k, v in (r.get("exts") or {}).items())
    a = decode(r["first"][0]) if r.get("first") else None
    b = decode(r["last"][-1]) if r.get("last") else None
    if a and b and a[0] == b[0] and n and n > 1:
        step = (b[1] - a[1]) / (n - 1)
        dec = "%s: %s → %s; step %s" % (a[0], a[1].strftime("%Y-%m-%d %H:%M"), b[1].strftime("%Y-%m-%d %H:%M"), step)
        expected = None
        if a[0].startswith("YYYYMMDD") or a[0].startswith("YYYYDDD ("):
            expected = (b[1] - a[1]).days + 1
            if expected != n:
                dec += " (**%d files for %d calendar days: %d missing**)" % (n, expected, expected - n)
    elif r.get("index_first") is not None:
        dec = "index %s → %s, usual step %s" % (r.get("index_first"), r.get("index_last"), list((r.get("index_steps") or {}).keys())[:1])
    else:
        dec = ""
    mod = ""
    if r.get("modified_first"):
        mod = r["modified_first"] if r["modified_first"] == r.get("modified_last") else "%s … %s" % (r["modified_first"], r.get("modified_last"))
    fl = ("`%s` → `%s`" % (r["first"][0], r["last"][-1])) if r.get("first") else ""
    L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
        esc(r["label"]), ("%sx%s" % (r.get("width"), r.get("height"))) if r.get("width") else "", files, esc(fmt),
        r.get("status"), esc(fl), esc(dec), esc(mod), r["url"]))
open(os.path.join(OUT, "frame-sets.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")

# ---------------------------------------------------------------- movies
L = ["# Every movie file in the EIC gallery (%d files)\n" % len(mv), HDR,
     "Duration, frame rate, frame count and codec were measured with ffmpeg from the file header (not taken from the page).",
     "- **frames** = duration × fps, rounded.",
     "- **codec**: h264 (MP4) and vp8/vp9 (WebM) play in every modern browser; hevc (H.265) only in some; prores, mpeg1video, wmv3, qtrle, mpeg4 do not play in browsers.",
     "- **Last-Modified** is the HTTP header of the file (UTC). For products that are re-rendered, this is when the newest render landed.\n"]
cur = None
for d in sorted(mv, key=lambda d: (d["page"], d["group"], (d.get("head") or {}).get("bytes") or 0)):
    if d["page"] != cur:
        cur = d["page"]
        L.append("\n## %d — %s\n" % (cur, pages[str(cur)]["title"]))
        L.append("| file | pixels | duration | fps | frames | codec | audio | size | Last-Modified (UTC) | media group | URL |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    p = probes.get(d["url"]) or {}
    h = d.get("head") or {}
    px = "%sx%s" % (p.get("width") or d.get("width"), p.get("height") or d.get("height"))
    lm = (h.get("last_modified") or "").replace(" GMT", "")
    L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
        esc(d["name"]), px, ("%.2f s" % p["duration_s"]) if p.get("duration_s") else "?", p.get("fps", "?"),
        p.get("frames_est", "?"), p.get("codec", "?"), "yes" if p.get("has_audio") else "no", human(h.get("bytes")),
        esc(lm), d["group"], d["url"]))
open(os.path.join(OUT, "movies.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
print("wrote gallery-tree.md, frame-sets.md (%d folders), movies.md (%d files)" % (len(allsets), len(mv)))
